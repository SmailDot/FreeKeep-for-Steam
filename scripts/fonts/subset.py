"""Subsets the bundled pixel fonts to the characters FreeKeep's interface uses.

    python3 scripts/fonts/subset.py      (or: npm run fonts)

Needs Python 3 with fonttools and brotli (`pip install fonttools brotli`) and Node (for the
relative-time strings Intl produces). Reads the full fonts in scripts/fonts/src/, writes the
subsets to public/fonts/ and the covered characters to src/lib/pixel-coverage.ts, which the popup
uses to show text the subset can't draw (mostly localized Epic game titles) in the system font.

Run it again whenever interface text changes; tests/fonts.test.ts fails until you do.
"""
import glob
import json
import os
import subprocess

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..'))
LANGS = ['en', 'zh-TW', 'zh-CN', 'de', 'es', 'fr', 'ja', 'ko', 'pl', 'pt-BR', 'ru', 'tr']

# Every relative time ("3 minutes ago") Intl can show in the settings page's status chips.
INTL = """
const langs = %s; let out = '';
for (const l of langs) {
  const rtf = new Intl.RelativeTimeFormat(l, { numeric: 'auto' });
  for (const u of ['minute', 'hour', 'day']) for (const n of [-1, -2, -5, -30, 0, 1]) out += rtf.format(n, u);
}
process.stdout.write(out);
""" % json.dumps(LANGS)


def interface_chars():
    chars = set()
    for path in glob.glob(os.path.join(ROOT, 'public/_locales/*/messages.json')):
        with open(path, encoding='utf-8') as f:
            for entry in json.load(f).values():
                chars |= set(entry['message'])
    chars |= set(subprocess.run(['node', '-e', INTL], capture_output=True, text=True, check=True).stdout)
    chars |= set('FreeKeep for Steam Epic Games ON OFF ▶✓─·!！…↳')
    return chars


# Fixed ranges, so Steam's English game names (and accented or Cyrillic ones) stay in pixels.
LATIN = list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) + list(range(0x2010, 0x2070)) + [0x2122, 0x2190, 0x2192, 0x2500, 0x25B6, 0x2713]
CYRILLIC = list(range(0x400, 0x460))


def make(name, unicodes):
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    font = TTFont(os.path.join(ROOT, 'scripts/fonts/src', name))
    subsetter = subset.Subsetter(opts)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    font.flavor = 'woff2'
    out = os.path.join(ROOT, 'public/fonts', name)
    font.save(out)
    print(f'{name}: {len(font.getBestCmap())} glyphs, {os.path.getsize(out) // 1024} KB')
    return set(font.getBestCmap())


def main():
    wanted = {ord(c) for c in interface_chars()}
    covered = make('Cubic_11.woff2', sorted(wanted | set(LATIN)))
    covered |= make('Galmuri11.woff2', sorted(wanted | set(LATIN) | set(CYRILLIC)))
    text = ''.join(chr(c) for c in sorted(covered) if c >= 0x20)
    with open(os.path.join(ROOT, 'src/lib/pixel-coverage.ts'), 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/fonts/subset.py: every character the bundled pixel fonts can draw.\n')
        f.write(f'export const PIXEL_COVERAGE = {json.dumps(text, ensure_ascii=False)};\n')
    print(f'coverage: {len(text)} characters')


if __name__ == '__main__':
    main()
